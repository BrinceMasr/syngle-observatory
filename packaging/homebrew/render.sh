#!/usr/bin/env bash
# Renders the Homebrew tap (BrinceMasr/homebrew-syngle-observatory) for one release: the `rustgis` cask
# (the signed and notarized Syngle Observatory.app from the macOS DMGs) and the `rustgis-cli` formula
# (the command line tool from the macOS CLI tarball).
#
#   packaging/homebrew/render.sh <version> <SHA256SUMS> <tap folder>
#
# Writes <tap>/Casks/rustgis.rb and <tap>/Formula/rustgis-cli.rb. The checksums come from the
# release's SHA256SUMS. REPO defaults to BrinceMasr/syngle-observatory.
set -euo pipefail

version="${1:?usage: render.sh <version> <SHA256SUMS> <tap folder>}"
version="${version#v}"
sums="${2:?usage: render.sh <version> <SHA256SUMS> <tap folder>}"
tap="${3:?usage: render.sh <version> <SHA256SUMS> <tap folder>}"
repo="${REPO:-BrinceMasr/syngle-observatory}"

# Only final releases: a pre-release suffix would make Homebrew treat it as the newest version.
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "not an X.Y.Z version: $version" >&2; exit 1; }
[[ "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || { echo "REPO is not owner/name: $repo" >&2; exit 1; }

# The checksum of one release file, failing when SHA256SUMS lacks it.
sha() {
  local h
  h="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
  [[ "$h" =~ ^[0-9a-f]{64}$ ]] || { echo "no checksum for $1 in $sums" >&2; return 1; }
  echo "$h"
}

dmg_arm="$(sha "syngle-observatory-$version-macos-aarch64.dmg")"
dmg_intel="$(sha "syngle-observatory-$version-macos-x86_64.dmg")"
cli_mac_arm="$(sha "rustgis-cli-$version-macos-aarch64.tar.gz")"
cli_mac_intel="$(sha "rustgis-cli-$version-macos-x86_64.tar.gz")"

mkdir -p "$tap/Casks" "$tap/Formula"
releases="https://github.com/$repo/releases/download/v#{version}"

# The cask follows Homebrew/homebrew-cask style (a plain desc, the default livecheck), so the same
# file can be submitted there once the repository meets its notability and age rules (#89).
cat > "$tap/Casks/rustgis.rb" <<RUBY
# Generated by packaging/homebrew/render.sh in $repo on every release; do not edit by hand.
cask "rustgis" do
  arch arm: "aarch64", intel: "x86_64"

  version "$version"
  sha256 arm:   "$dmg_arm",
         intel: "$dmg_intel"

  url "$releases/syngle-observatory-#{version}-macos-#{arch}.dmg"
  name "Syngle Observatory"
  desc "GIS platform"
  homepage "https://github.com/BrinceMasr/syngle-observatory/"

  depends_on macos: :big_sur

  app "Syngle Observatory.app"

  zap trash: [
    "~/Library/Application Support/Syngle Observatory",
    "~/Library/Caches/Syngle Observatory",
    "~/Library/Saved Application State/com.syngle.observatory.savedState",
  ]
end
RUBY

cat > "$tap/Formula/rustgis-cli.rb" <<RUBY
# Generated by packaging/homebrew/render.sh in $repo on every release; do not edit by hand.
class RustgisCli < Formula
  desc "Command-line tool and MCP server for the Syngle Observatory geographic information system"
  homepage "https://github.com/BrinceMasr/syngle-observatory/"
  version "$version"
  license "Apache-2.0"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "$releases/rustgis-cli-#{version}-macos-aarch64.tar.gz"
      sha256 "$cli_mac_arm"
    end
    on_intel do
      url "$releases/rustgis-cli-#{version}-macos-x86_64.tar.gz"
      sha256 "$cli_mac_intel"
    end
  end

  def install
    bin.install "rustgis-cli"
  end

  test do
    assert_match "project.new", shell_output("#{bin}/rustgis-cli commands")
  end
end
RUBY
